/* 按成就 ID 取定义, 找不到返回 nullptr; 条目有序, 用二分查找. */
inline const AchievementDef* FindAchievement(int32_t id) {
    int32_t low = 0;
    int32_t high = kAchievementCount - 1;
    while (low <= high) {
        const int32_t mid = low + (high - low) / 2;
        if (kAchievements[mid].id == id) {
            return &kAchievements[mid];
        }
        if (kAchievements[mid].id < id) {
            low = mid + 1;
        } else {
            high = mid - 1;
        }
    }
    return nullptr;
}

