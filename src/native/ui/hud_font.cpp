const uint8_t* GlyphRows(char character) {
    const char upper = (character >= 'a' && character <= 'z')
                           ? static_cast<char>(character - 'a' + 'A')
                           : character;
    for (int32_t index = 0; index < GlyphCount(); ++index) {
        if (kGlyphs[index].code == upper) {
            return kGlyphs[index].rows;
        }
    }
    return nullptr;
}

float MeasureText(const char* text, float pixelSize) {
    if (text == nullptr || text[0] == '\0') {
        return 0.0f;
    }
    int32_t length = 0;
    for (const char* cursor = text; *cursor != '\0'; ++cursor) {
        ++length;
    }
    const float advance = static_cast<float>(kGlyphWidth + kGlyphSpacing) * pixelSize;
    return static_cast<float>(length) * advance - static_cast<float>(kGlyphSpacing) * pixelSize;
}

